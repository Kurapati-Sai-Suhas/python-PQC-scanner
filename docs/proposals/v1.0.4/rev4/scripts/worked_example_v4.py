# ------------------------------------------------------------------------------------------- 1. scoring table
TRUTHS = [  # label, site fields
    ("SIGN or VERIFY, DETERMINATE (expected SIG)", dict(eligible="yes", gt_role="SIGN", assessability="DETERMINATE", hybrid_component="no")),
    ("KEY_ESTABLISHMENT / PK_*, DETERMINATE (expected KEM)", dict(eligible="yes", gt_role="KEY_ESTABLISHMENT", assessability="DETERMINATE", hybrid_component="no")),
    ("KEY_MATERIAL_ONLY or PROTOCOL_CONFIG (expected NONE)", dict(eligible="yes", gt_role="KEY_MATERIAL_ONLY", assessability="DETERMINATE", hybrid_component="no")),
    ("approved hybrid component (expected NONE)", dict(eligible="yes", gt_role="KEY_ESTABLISHMENT", assessability="DETERMINATE", hybrid_component="yes")),
    ("INDETERMINATE, role not inventory/hybrid (expected ABSTAIN)", dict(eligible="yes", gt_role="UNKNOWN", assessability="INDETERMINATE", hybrid_component="no")),
    ("UNKNOWN role recorded as DETERMINATE (expected ABSTAIN; guide edge case)", dict(eligible="yes", gt_role="UNKNOWN", assessability="DETERMINATE", hybrid_component="no")),
    ("ineligible (expected N/A)", dict(eligible="no", gt_role="NONE", assessability="DETERMINATE", hybrid_component="no")),
]
ACTS = [("RECOMMEND", "SIG"), ("RECOMMEND", "KEM"), ("RECOMMEND", "DUAL"), ("RECOMMEND", "PQC_ALREADY"),
        ("FLAG_NO_TARGET", "NONE"), ("ABSTAIN", "NONE"), ("NO_FINDING", "NONE"), ("EXECUTION_FAILURE", "NONE")]


def scoring_table() -> list[str]:
    head = "| Ground truth | " + " | ".join(f"{a}" + (f" {c}" if a == "RECOMMEND" else "") for a, c in ACTS) + " |"
    lines = ["# Frozen scoring, every action x ground truth (generated by pqscan.bench.judge.judge)", "",
             "PROPOSED, NOT ADOPTED audit material. Cells: judgment[/harm]. **Bold** = counts as CORRECT in correct-per-eligible-site.",
             "", head, "|" + "---|" * (len(ACTS) + 1)]
    for name, site in TRUTHS:
        cells = []
        for a, c in ACTS:
            j = MR.judge(site, a, c)
            t = j.judgment + (f"/{j.harm}" if j.harm else "")
            cells.append(f"**{t}**" if j.judgment == "CORRECT" else t)
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    hyb = MR.judge(dict(eligible="yes", gt_role="SIGN", assessability="DETERMINATE", hybrid_component="yes"), "RECOMMEND", "PQC_ALREADY")
    lines += ["", f"Check: RECOMMEND PQC_ALREADY on a hybrid SIGN site -> {hyb.judgment} (hybrid rule is role-independent).",
              "Strict sensitivity scoring changes only CORRECT KEM recommendations with drop-in wording (not shown; arms here emit no such text)."]
    return lines


# ------------------------------------------------------------------------------------------- 2. worked example
def S(sid, role, ass, hyb="no"):
    return dict(site_id=sid, eligible="yes", gt_role=role, assessability=ass, hybrid_component=hyb)


EX_SITES = [S("s1", "SIGN", "DETERMINATE"), S("s2", "SIGN", "DETERMINATE"), S("s3", "KEY_ESTABLISHMENT", "DETERMINATE"),
            S("s4", "VERIFY", "DETERMINATE"), S("s5", "SIGN", "DETERMINATE"), S("s6", "UNKNOWN", "INDETERMINATE"),
            S("s7", "PK_ENCRYPT", "DETERMINATE"), S("s8", "SIGN", "DETERMINATE"), S("s9", "SIGN", "DETERMINATE"),
            S("s10", "UNKNOWN", "INDETERMINATE"), S("s11", "KEY_MATERIAL_ONLY", "DETERMINATE"), S("s12", "VERIFY", "DETERMINATE")]
EX_F = [A("RECOMMEND", "SIG", "T3"), A("RECOMMEND", "SIG", "T3"), A("RECOMMEND", "KEM", "T2"), A("RECOMMEND", "KEM", "T2"),
        A("RECOMMEND", "SIG", "T2"), A("ABSTAIN", "NONE", "T2"), A("RECOMMEND", "KEM", "T3"), A("RECOMMEND", "SIG", "T2"),
        A("ABSTAIN", "NONE", "T1"), A("RECOMMEND", "SIG", "T1"), A("FLAG_NO_TARGET", "NONE", "T2"), A("ABSTAIN", "NONE", "T2")]
EX_M = [A("RECOMMEND", "SIG", "T1"), A("ABSTAIN", "NONE", "T1"), A("RECOMMEND", "SIG", "T1"), A("ABSTAIN", "NONE", "T1"),
        A("RECOMMEND", "SIG", "T0"), A("ABSTAIN", "NONE", "T1"), A("ABSTAIN", "NONE", "T1"), A("RECOMMEND", "SIG", "T1"),
        A("ABSTAIN", "NONE", "T0"), A("ABSTAIN", "NONE", "T1"), A("ABSTAIN", "NONE", "T1"), A("RECOMMEND", "SIG", "T1")]


def _act(a: A) -> str:
    return {"RECOMMEND": f"REC {a.rec_class} ({a.tier})", "FLAG_NO_TARGET": f"FLAG ({a.tier})",
            "ABSTAIN": f"ABSTAIN ({a.tier})", "NO_FINDING": "NO_FINDING"}[a.action]


def worked_example() -> tuple[list[str], dict]:
    r = MR.matched_comparison(EX_SITES, EX_F, EX_M, comparison="H2-1", repo="example")
    m = r["match"]
    n = r["n"]
    keys = {s["site_id"]: MR.tiebreak_key(MR.PRIMARY_SEED, "H2-1", "example", s["site_id"]) for s in EX_SITES}
    lines = ["# Extended worked example (hypothetical; 12 eligible sites, one repository)", "",
             "PROPOSED, NOT ADOPTED. Generated by `scripts/worked_example_v4.py` with the reference implementation "
             "`scripts/matching_ref_v4.py`; judgments come from the frozen `pqscan.bench.judge.judge`.", "",
             "F = Module C `full` at T0; M = `method+args` at T0. Comparison label `H2-1`, repository `example`, seed `20261113`.", "",
             "## A. Inputs and natural judgments", "",
             "| site | truth | F natural | F judgment | M natural | M judgment |", "|---|---|---|---|---|---|"]
    for s, row in zip(EX_SITES, r["rows"]):
        truth = f"{s['gt_role']}, {s['assessability'][:5].lower()}."
        lines.append(f"| {s['site_id']} | {truth} | {_act(row['F_natural'])} | {row['F_judgment_natural']} | "
                     f"{_act(row['M_natural'])} | {row['M_judgment_natural']} |")
    rec_f = [s["site_id"] for s, a in zip(EX_SITES, EX_F) if a.action == "RECOMMEND"]
    rec_m = [s["site_id"] for s, a in zip(EX_SITES, EX_M) if a.action == "RECOMMEND"]
    lines += ["", "## B. Matching", "",
              f"- Natural RECOMMEND counts: R_F = {m.R_f} ({', '.join(rec_f)}); R_M = {m.R_m} ({', '.join(rec_m)}).",
              f"- Natural coverage: F {m.R_f}/{n} = {m.R_f / n:.3f}; M {m.R_m}/{n} = {m.R_m / n:.3f}.",
              f"- k = min({m.R_f}, {m.R_m}) = {m.k}. F withdraws R_F - k = {m.R_f - m.k}; M withdraws {m.R_m - m.k}.",
              "- F's recommendations in withdrawal order (tier ascending, then SHA-256 key ascending):", "",
              "| order | site | tier | SHA-256('20261113|H2-1|example|site')[:12] | withdrawn |", "|---|---|---|---|---|"]
    order = sorted([(s["site_id"], a) for s, a in zip(EX_SITES, EX_F) if a.action == "RECOMMEND"],
                   key=lambda x: (MR.TIER_RANK[x[1].tier], keys[x[0]]))
    for i, (sid, a) in enumerate(order, 1):
        lines.append(f"| {i} | {sid} | {a.tier} | {keys[sid][:12]} | {'yes' if sid in m.withdrawn_f else 'no'} |")
    lines += ["", f"- Withdrawn: {', '.join(m.withdrawn_f)}. Boundary tier {m.boundary_tier}: {m.withdrawn_at_boundary} "
              f"of {m.tied_at_boundary} tied recommendations withdrawn.",
              f"- Matched coverage: F {m.k}/{n}, M {m.k}/{n} = {m.k / n:.3f} each."]
    lines += ["", f"- Recommended by both after matching: {', '.join(sorted(r['both_rec'], key=lambda x: int(x[1:]))) or 'none'}; "
              f"F only: {', '.join(sorted(r['f_only_rec'], key=lambda x: int(x[1:]))) or 'none'}; "
              f"M only: {', '.join(sorted(r['m_only_rec'], key=lambda x: int(x[1:]))) or 'none'}.",
              "  Equal recommendation **counts**, different recommended **sites**."]
    lines += ["", "## C. Correctness before and after matching (1 = CORRECT)", "",
              "| site | F natural | F matched action | F matched judgment | X_nat | X | M matched action | M matched judgment | Y_nat | Y | pair (X,Y) |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for row in r["rows"]:
        lines.append(f"| {row['site_id']} | {_act(row['F_natural'])} | {_act(row['F_matched'])}{' (withdrawn)' if row['F_withdrawn'] else ''} | "
                     f"{row['F_judgment_matched']} | {row['X_nat']} | {row['X']} | {_act(row['M_matched'])} | {row['M_judgment_matched']} | "
                     f"{row['Y_nat']} | {row['Y']} | ({row['X']},{row['Y']}) |")
    a11 = sum(1 for x in r["rows"] if x["X"] == 1 and x["Y"] == 1)
    a00 = sum(1 for x in r["rows"] if x["X"] == 0 and x["Y"] == 0)
    lines += ["", "## D. Paired outcome table (matched)", "", "| | M correct | M not correct | total |", "|---|---|---|---|",
              f"| F correct | {a11} | b = {r['b']} | {a11 + r['b']} |",
              f"| F not correct | c = {r['c']} | {a00} | {r['c'] + a00} |",
              f"| total | {a11 + r['c']} | {r['b'] + a00} | {n} |", "",
              f"- Matched: F {r['X']}/{n}, M {r['Y']}/{n}; delta = ({r['X']} - {r['Y']})/{n} = {r['delta']:+.4f} = (b - c)/n = ({r['b']} - {r['c']})/{n}.",
              f"- Natural (secondary): F {r['X_nat']}/{n}, M {r['Y_nat']}/{n}; delta_nat = {(r['X_nat'] - r['Y_nat']) / n:+.4f}.",
              "", "## E. Decomposition of the matched difference by the action each arm finally took", "",
              "| final action | F correct | M correct | contribution to delta |", "|---|---|---|---|"]
    for cat, (x, y) in r["decomposition"].items():
        lines.append(f"| {cat} | {x} | {y} | {(x - y) / n:+.4f} |")
    lines += [f"| total | {r['X']} | {r['Y']} | {r['delta']:+.4f} |", "",
              f"- Recommendation part only: F {r['rec_correct_f']}/{m.k} correct recommendations, M {r['rec_correct_m']}/{m.k} "
              f"(matched precision difference {(r['rec_correct_f'] - r['rec_correct_m']) / m.k:+.3f}; "
              f"contribution to delta {(r['rec_correct_f'] - r['rec_correct_m']) / n:+.4f})."]
    tav = MR.tie_average_delta(EX_SITES, EX_F, EX_M, comparison="H2-1", repo="example")
    sens = [MR.matched_comparison(EX_SITES, EX_F, EX_M, comparison="H2-1", repo="example", seed=s)["delta"] for s in MR.SENSITIVITY_SEEDS]
    import numpy as np
    sens = np.array(sens)
    vals, cnts = np.unique(np.round(sens, 4), return_counts=True)
    lines += ["", "## F. Seed sensitivity for this example", "",
              f"- Primary seed 20261113: delta = {r['delta']:+.4f}.",
              f"- 100 sensitivity seeds (20261113-S001 ... S100): median {np.median(sens):+.4f}, min {sens.min():+.4f}, max {sens.max():+.4f}; "
              "distribution " + ", ".join(f"{v:+.4f} x{c}" for v, c in zip(vals, cnts)) + ".",
              f"- Exact tie-average (expectation over all tie-breaks, no seed): {tav:+.4f}."]
    return lines, r


# ------------------------------------------------------------------------------------------- 3. pilot demonstration
def pilot() -> list[str]:
    path = ROOT / "docs" / "dev" / "pilot_harness" / "judgments.csv"
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    by = {}
    for x in rows:
        by.setdefault((x["method"], x["site_id"]), x)
    lines = ["# Pilot (development) demonstration of matching — development data, circular, NOT a result", "",
             "PROPOSED, NOT ADOPTED. Source: `docs/dev/pilot_harness/judgments.csv` (30 eligible pilot sites; pqscan was "
             "developed on them, so every figure is circular). F = `pqscan:B3-full-noabst` (full, T0); "
             "M = `pqscan:B2-method-args` (method+args, T0): exactly the V18 arms of hypothesis B1.", ""]
    tot = {"n": 0, "X": 0, "Y": 0, "Xn": 0, "Yn": 0, "k": 0, "RF": 0, "RM": 0, "dec": {}}
    for repo in ("paramiko", "python-jose"):
        sites, f, mm = [], [], []
        for x in rows:
            if x["repo"] != repo or x["method"] != "pqscan:B3-full-noabst" or x["eligible"] != "yes":
                continue
            y = by[("pqscan:B2-method-args", x["site_id"])]
            sites.append(dict(site_id=x["site_id"], eligible="yes", gt_role=x["gt_role"], assessability=x["assessability"],
                              hybrid_component=x["hybrid_component"]))
            f.append(A(x["tool_action"], x["rec_class"], x["tier"] or None))
            mm.append(A(y["tool_action"], y["rec_class"], y["tier"] or None))
        r = MR.matched_comparison(sites, f, mm, comparison="H2-1", repo=repo)
        m = r["match"]
        tav = MR.tie_average_delta(sites, f, mm, comparison="H2-1", repo=repo)
        lines += [f"## {repo} ({r['n']} eligible sites)", "",
                  f"- R_F = {m.R_f}, R_M = {m.R_m}, k = {m.k} (matched coverage {m.k / r['n']:.3f}); F withdraws {len(m.withdrawn_f)} "
                  f"({', '.join(m.withdrawn_f)}), boundary tier {m.boundary_tier} ({m.withdrawn_at_boundary} of {m.tied_at_boundary} tied).",
                  f"- Natural M recommendations are a subset of natural F recommendations: "
                  f"{ {s['site_id'] for s, a in zip(sites, mm) if a.action == 'RECOMMEND'} <= {s['site_id'] for s, a in zip(sites, f) if a.action == 'RECOMMEND'} }.",
                  f"- Natural: F {r['X_nat']}/{r['n']}, M {r['Y_nat']}/{r['n']} (delta_nat {(r['X_nat'] - r['Y_nat']) / r['n']:+.3f}).",
                  f"- Matched: F {r['X']}/{r['n']}, M {r['Y']}/{r['n']} (delta {r['delta']:+.3f}; tie-average {tav:+.3f}); b = {r['b']}, c = {r['c']}.",
                  f"- Matched recommendations correct: F {r['rec_correct_f']}/{m.k}, M {r['rec_correct_m']}/{m.k}.",
                  "- Decomposition (F correct, M correct): " + "; ".join(f"{k} {v}" for k, v in r["decomposition"].items()), ""]
        tot["n"] += r["n"]; tot["X"] += r["X"]; tot["Y"] += r["Y"]; tot["Xn"] += r["X_nat"]; tot["Yn"] += r["Y_nat"]
        tot["k"] += m.k; tot["RF"] += m.R_f; tot["RM"] += m.R_m
        for kk, v in r["decomposition"].items():
            a0, b0 = tot["dec"].get(kk, (0, 0)); tot["dec"][kk] = (a0 + v[0], b0 + v[1])
    n = tot["n"]
    lines += ["## Pooled (site-weighted)", "",
              f"- Natural coverage F {tot['RF']}/{n} = {tot['RF'] / n:.3f}, M {tot['RM']}/{n} = {tot['RM'] / n:.3f}; matched coverage {tot['k']}/{n} = {tot['k'] / n:.3f}.",
              f"- Natural correct-per-eligible: F {tot['Xn']}/{n}, M {tot['Yn']}/{n}, delta_nat = {(tot['Xn'] - tot['Yn']) / n:+.3f}.",
              f"- Matched correct-per-eligible: F {tot['X']}/{n}, M {tot['Y']}/{n}, delta = {(tot['X'] - tot['Y']) / n:+.3f}.",
              "- Matched decomposition (F, M correct): " + "; ".join(f"{k} {v}" for k, v in tot["dec"].items()) + ".", "",
              "**Reading.** On the pilot both arms' recommendations are all correct, so at equal recommendation count their "
              "recommendation parts are identical. The whole matched difference comes from non-recommendation actions "
              "(F's correct FLAG_NO_TARGET on KEY_MATERIAL_ONLY sites, where M abstains and is UNASSESSABLE). The large natural "
              "difference is a coverage effect, which matching removes by design.", "",
              "On the pilot, method-only and method+args+recv make the same role decisions as method+args (they differ only in "
              "tiers; `docs/dev/roles_on_pilot.csv`), and the comparator never withdraws, so B3 and B4 would give the same matched "
              "outcomes as B1 here."]
    # check the role equality claim
    rp = list(csv.DictReader((ROOT / "docs" / "dev" / "roles_on_pilot.csv").open(encoding="utf-8")))
    same = all(x["method-only:role"] == x["method+args:role"] == x["method+args+recv:role"] for x in rp)
    lines.append(f"\nCheck (roles_on_pilot.csv): method-only, method+args and method+args+recv roles identical on all {len(rp)} sites: {same}.")
    return lines


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "scoring_table_v4.md").write_text("\n".join(scoring_table()) + "\n", encoding="utf-8")
    ex, _ = worked_example()
    (OUT / "worked_example_v4.md").write_text("\n".join(ex) + "\n", encoding="utf-8")
    (OUT / "pilot_matching_v4.md").write_text("\n".join(pilot()) + "\n", encoding="utf-8")
    print("wrote scoring_table_v4.md, worked_example_v4.md, pilot_matching_v4.md")


if __name__ == "__main__":
    main()
