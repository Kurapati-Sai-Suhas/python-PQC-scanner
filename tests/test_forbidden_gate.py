"""Forbidden-token gate before the AI review (owner decision F07; guide v1.2 Sec. 6). Genuine forbidden content is
always excluded from the AI review; only a verified false positive (with file:line evidence) may proceed; the decision
file is hashed into the ledger; nothing is redacted."""
from __future__ import annotations

import csv
from pathlib import Path
from types import SimpleNamespace

import pytest

from pqscan.bench import annotate as AN
from pqscan.bench import ledger as L

CLEAN = {"candidate_id": "C-000000000001", "text": "1: k = rsa.generate_private_key(65537, 3072)\n", "warnings": []}
NOISY = {"candidate_id": "C-000000000002", "text": "1: # generated by semgrep\n2: k.sign(m)\n", "warnings": ["x"]}


def _ctx(tmp_path: Path, decision: Path | None = None):
    work = tmp_path / "work"
    work.mkdir(exist_ok=True)
    p = {"work": work, "ledger": tmp_path / "ledger.jsonl"}
    a = SimpleNamespace(repo="demo", phase="DV", batch="B1", warnings_decision=str(decision) if decision else None)
    return a, p


def _decision(tmp_path: Path, rows: list[dict], name: str = "decision.csv") -> Path:
    f = tmp_path / name
    with f.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=AN.DECISION_COLUMNS)
        w.writeheader()
        w.writerows(rows)
    return f


def test_clean_packets_pass_without_a_decision(tmp_path):
    a, p = _ctx(tmp_path)
    send, excluded, info = AN._forbidden_gate(a, p, [CLEAN])
    assert send == [CLEAN] and excluded == [] and info == {} and not p["ledger"].exists()


def test_warned_packet_refused_without_a_decision(tmp_path):
    a, p = _ctx(tmp_path)
    with pytest.raises(SystemExit, match="forbidden token"):
        AN._forbidden_gate(a, p, [CLEAN, NOISY])


def test_genuine_token_is_excluded_even_with_a_reason(tmp_path):
    d = _decision(tmp_path, [{"candidate_id": NOISY["candidate_id"], "token": "semgrep", "verdict": "genuine",
                              "evidence": "pkg/a.py:1 but I think it is harmless"}])
    a, p = _ctx(tmp_path, d)
    send, excluded, info = AN._forbidden_gate(a, p, [CLEAN, NOISY])
    assert [pk["candidate_id"] for pk in send] == [CLEAN["candidate_id"]] and excluded == [NOISY["candidate_id"]]
    assert NOISY["text"] not in "".join(pk["text"] for pk in send)                     # nothing redacted, just excluded
    rec = L.read(p["ledger"])[-1]
    assert rec["step"] == "note" and rec["sha256"] == L.file_sha256(p["work"] / "forbidden_decision_demo_B1.csv")
    assert info["decision_sha256"] == rec["sha256"] and "excluded ['C-000000000002']" in rec["note"]
    assert AN._excluded(p, a) == [NOISY["candidate_id"]]


def test_false_positive_needs_file_line_evidence(tmp_path):
    bad = _decision(tmp_path, [{"candidate_id": NOISY["candidate_id"], "token": "semgrep", "verdict": "false_positive",
                                "evidence": "looks harmless"}])
    a, p = _ctx(tmp_path, bad)
    with pytest.raises(SystemExit, match="file:line"):
        AN._forbidden_gate(a, p, [NOISY])
    ok = _decision(tmp_path, [{"candidate_id": NOISY["candidate_id"], "token": "semgrep", "verdict": "false_positive",
                               "evidence": "pkg/a.py:1 is a vendored licence header, not the evaluated tool"}], "ok.csv")
    a, p = _ctx(tmp_path, ok)
    send, excluded, info = AN._forbidden_gate(a, p, [NOISY])
    assert send == [NOISY] and excluded == [] and info["false_positive"] == [NOISY["candidate_id"]]


@pytest.mark.parametrize("rows", [
    [],                                                                                  # pair not covered
    [{"candidate_id": NOISY["candidate_id"], "token": "qsafe", "verdict": "genuine", "evidence": ""}],   # wrong token
    [{"candidate_id": NOISY["candidate_id"], "token": "semgrep", "verdict": "maybe", "evidence": "a.py:1"}],
])
def test_incomplete_or_invalid_decisions_refused(tmp_path, rows):
    a, p = _ctx(tmp_path, _decision(tmp_path, rows))
    with pytest.raises(SystemExit):
        AN._forbidden_gate(a, p, [NOISY])


def test_a_recorded_decision_cannot_be_silently_replaced(tmp_path):
    g = _decision(tmp_path, [{"candidate_id": NOISY["candidate_id"], "token": "semgrep", "verdict": "genuine",
                              "evidence": ""}])
    a, p = _ctx(tmp_path, g)
    AN._forbidden_gate(a, p, [NOISY])
    fp = _decision(tmp_path, [{"candidate_id": NOISY["candidate_id"], "token": "semgrep", "verdict": "false_positive",
                               "evidence": "a.py:1 unrelated"}], "fp.csv")
    a2, _ = _ctx(tmp_path, fp)
    with pytest.raises(SystemExit, match="different decision"):
        AN._forbidden_gate(a2, p, [NOISY])
